export function itemsBySystem(system: SystemId): AnatomyItem[] {
  return ITEMS.filter((i) => i.system === system);
}

export function itemsByRegion(region: RegionId): AnatomyItem[] {
  return ITEMS.filter((i) => i.region === region);
}

export function getItem(id: string): AnatomyItem | undefined {
  return ITEMS.find((i) => i.id === id);
}

export function getSystem(id: SystemId): SystemDef {
  return SYSTEMS.find((s) => s.id === id)!;
}
